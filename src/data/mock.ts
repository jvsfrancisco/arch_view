function makeStages(base: number): Stage[] {
  const defs: [Stage['key'], string, number][] = [
    ['demolicao', 'Demolição', 100],
    ['alvenaria', 'Alvenaria', 100],
    ['eletrica', 'Elétrica', base > 60 ? 90 : 55],
    ['hidraulica', 'Hidráulica', base > 60 ? 85 : 40],
    ['gesso', 'Gesso', base > 60 ? 70 : 20],
    ['pintura', 'Pintura', base > 60 ? 40 : 0],
    ['marcenaria', 'Marcenaria', base > 60 ? 25 : 0],
    ['decoracao', 'Decoração', 0],
  ]
  return defs.map(([key, label, progress], i) => ({
    key,
    label,
    progress,
    start: `2026-0${Math.min(9, 3 + Math.floor(i / 2))}-0${(i % 4) + 1}`,
    end: `2026-0${Math.min(9, 4 + Math.floor(i / 2))}-2${i % 8}`,
  }))
}

